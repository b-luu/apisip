//! DuckDB SQL views over the append-only output, written to
//! `_apisip/views/` after each run:
//!
//! - `<stream>_current.sql`: one row per primary key, its latest version;
//! - `<stream>_history.sql`: one row per version, with `valid_from`,
//!   `valid_to` and `is_current` (a type 2 slowly changing dimension);
//! - `all.sql`: `create or replace view` statements for every stream, for
//!   `duckdb -c ".read _apisip/views/all.sql"`.

use anyhow::Result;

use crate::config::{Config, Format, Mode, StreamConfig};
use crate::schema::{EXTRACTED_AT, RUN_ID};
use crate::sink::Store;
use crate::state::State;

pub const VIEWS_DIR: &str = "_apisip/views";

/// Writes the views of every stream that has committed data.
pub async fn write_all(store: &Store, config: &Config, state: &State) -> Result<Vec<String>> {
    let base = base_location(store);
    let format = config.destination.format;
    let mut all = String::from(HEADER);
    let mut written = Vec::new();
    for s in &config.streams {
        let Some(st) = state.streams.get(&s.name) else {
            continue;
        };
        let Some(last_run) = st.last_run_id.as_deref() else {
            continue;
        };
        // DuckDB fails on a glob that matches nothing, and the statements
        // after it in all.sql would never run.
        if !has_data_files(store, &s.name, format).await? {
            continue;
        }
        let source = read_files(&base, &s.name, format);
        let views = [
            ("current", current_sql(s, &source, last_run)),
            ("history", history_sql(s, &source)),
        ];
        for (kind, sql) in views {
            let Some(sql) = sql else { continue };
            let path = format!("{VIEWS_DIR}/{}_{kind}.sql", s.name);
            store.put(&path, format!("{HEADER}{sql};\n")).await?;
            all.push_str(&format!(
                "create or replace view {} as\n{sql};\n\n",
                ident(&format!("{}_{kind}", s.name))
            ));
            written.push(path);
        }
    }
    if !written.is_empty() {
        store.put(&format!("{VIEWS_DIR}/all.sql"), all).await?;
    }
    Ok(written)
}

async fn has_data_files(store: &Store, stream: &str, format: Format) -> Result<bool> {
    let ext = format!(".{}", format.extension());
    Ok(store.list(stream).await?.iter().any(|m| {
        let p = m.location.as_ref();
        p.contains("/dt=") && p.ends_with(&ext)
    }))
}

const HEADER: &str = "-- Generated by apisip after each run; edits are overwritten.\n\n";

/// Where DuckDB finds the destination: an absolute folder, or the s3:// URL.
fn base_location(store: &Store) -> String {
    match &store.local_root {
        Some(p) => p.display().to_string(),
        None => store.url.trim_end_matches('/').to_string(),
    }
}

/// The committed data files of a stream. `dt=*/` keeps `_quarantine/` out.
fn read_files(base: &str, stream: &str, format: Format) -> String {
    let glob = literal(&format!("{base}/{stream}/dt=*/**/*.{}", format.extension()));
    match format {
        Format::Parquet => {
            format!("read_parquet({glob}, union_by_name = true, hive_partitioning = false)")
        }
        Format::Jsonl => format!(
            "read_json({glob}, format = 'newline_delimited', union_by_name = true, hive_partitioning = false)"
        ),
    }
}

fn current_sql(s: &StreamConfig, source: &str, last_run: &str) -> Option<String> {
    if s.mode() == Mode::FullRefresh {
        // The latest committed snapshot.
        return Some(format!(
            "select * from {source}\nwhere {RUN_ID} = {}",
            literal(last_run)
        ));
    }
    let key = key_list(s)?;
    let order = match s.cursor() {
        Some(c) => format!("{} desc nulls last, {EXTRACTED_AT} desc", path_expr(c)),
        None => format!("{EXTRACTED_AT} desc"),
    };
    Some(format!(
        "select * exclude (_apisip_rn) from (\n  \
           select *, row_number() over (partition by {key} order by {order}) as _apisip_rn\n  \
           from {source}\n\
         ) where _apisip_rn = 1"
    ))
}

fn history_sql(s: &StreamConfig, source: &str) -> Option<String> {
    let key = key_list(s)?;
    if s.mode() == Mode::FullRefresh {
        // Compare consecutive snapshots: a row is a new version when its
        // content differs from the same key in the previous snapshot. Runs
        // are ordered by extraction time: run ids only sort to the second.
        return Some(format!(
            "with snapshots as (\n  \
               select *,\n    \
                 md5(to_json(struct_pack(*columns(* exclude ({RUN_ID}, {EXTRACTED_AT}))))) as _apisip_hash,\n    \
                 arg_max({RUN_ID}, {EXTRACTED_AT}) over () as _apisip_latest_run,\n    \
                 arg_max({RUN_ID}, {EXTRACTED_AT}) over (partition by {key}) as _apisip_last_seen\n  \
               from {source}\n\
             ), changes as (\n  \
               select *, lag(_apisip_hash) over (partition by {key} order by {EXTRACTED_AT}) as _apisip_prev\n  \
               from snapshots\n\
             ), versions as (\n  \
               select *,\n    \
                 {EXTRACTED_AT} as valid_from,\n    \
                 lead({EXTRACTED_AT}) over (partition by {key} order by {EXTRACTED_AT}) as valid_to\n  \
               from changes\n  \
               where _apisip_prev is distinct from _apisip_hash\n\
             )\n\
             select * exclude (_apisip_hash, _apisip_prev, _apisip_latest_run, _apisip_last_seen),\n  \
               valid_to is null and _apisip_last_seen = _apisip_latest_run as is_current\n\
             from versions"
        ));
    }
    let cursor = path_expr(s.cursor()?);
    Some(format!(
        "with versions as (\n  \
           select * exclude (_apisip_rn) from (\n    \
             select *, row_number() over (partition by {key}, {cursor} order by {EXTRACTED_AT}) as _apisip_rn\n    \
             from {source}\n  \
           ) where _apisip_rn = 1\n\
         ), ranged as (\n  \
           select *,\n    \
             {cursor} as valid_from,\n    \
             lead({cursor}) over (partition by {key} order by {cursor}) as valid_to\n  \
           from versions\n\
         )\n\
         select *, valid_to is null as is_current\n\
         from ranged"
    ))
}

fn key_list(s: &StreamConfig) -> Option<String> {
    if s.primary_key.is_empty() {
        return None;
    }
    Some(
        s.primary_key
            .iter()
            .map(|k| path_expr(k))
            .collect::<Vec<_>>()
            .join(", "),
    )
}

/// `a.b` (a dotted record path) as `"a"."b"`.
fn path_expr(dotted: &str) -> String {
    dotted.split('.').map(ident).collect::<Vec<_>>().join(".")
}

fn ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stream(toml: &str) -> StreamConfig {
        toml::from_str(toml).unwrap()
    }

    #[test]
    fn incremental_views_partition_by_key_and_order_by_cursor() {
        let s = stream(
            r#"name = "users"
path = "/users"
primary_key = "id"
incremental = { cursor = "meta.updated_at", param = "since" }"#,
        );
        let src = read_files("/data", "users", Format::Parquet);
        assert!(src.contains("'/data/users/dt=*/**/*.parquet'"));
        let current = current_sql(&s, &src, "r1").unwrap();
        assert!(current.contains(
            r#"partition by "id" order by "meta"."updated_at" desc nulls last, _apisip_extracted_at desc"#
        ));
        let history = history_sql(&s, &src).unwrap();
        assert!(history.contains(r#"lead("meta"."updated_at") over (partition by "id""#));
    }

    #[test]
    fn full_refresh_current_is_the_last_committed_snapshot() {
        let s = stream("name = \"plans\"\npath = \"/plans\"\nprimary_key = \"id\"");
        let src = read_files("/data", "plans", Format::Jsonl);
        assert!(
            current_sql(&s, &src, "it's")
                .unwrap()
                .ends_with("= 'it''s'")
        );
        assert!(history_sql(&s, &src).unwrap().contains("lag(_apisip_hash)"));
    }

    #[test]
    fn no_primary_key_means_no_dedup_views() {
        let s = stream(
            "name = \"events\"\npath = \"/events\"\nincremental = { cursor = \"at\", param = \"since\" }",
        );
        assert!(current_sql(&s, "x", "r").is_none());
        assert!(history_sql(&s, "x").is_none());
    }
}
